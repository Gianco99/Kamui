## Standard Python imports
import json
import os
import re
import shutil
import stat
import tarfile

## Kamui modules
from ..configReaders.sites import loadSites
from ..foundations import paths
from ..submit.common import checkOutputUnused, checkTaskName, chunk, eosListing, outputDir, publishRecord, readTaskRecord, recordedOutputDir, runTool, updateTaskRecord
from .io import CUTFLOW_NAME, SELECTED_NAME, checkFreshTask, writePassRecord

## Input files per job when the flag does not say otherwise
DEFAULT_FILES_PER_JOB = 5
## Memory each job asks condor for, in MB, when --memoryMB does not say otherwise
DEFAULT_MEMORY_MB = 2000

## The folder under the output base that condor selection passes write to, <base>/selected/<task>
OUTPUT_STAGE = "selected"

RUN_SCRIPT = '#!/bin/bash\n# Generated by kamui. $1 = sample name, $2 = job index\nset -e\nSAMPLE=$1\nIDX=$2\necho "[job] sample=$SAMPLE index=$IDX host=$(hostname) start=$(date)"\n\nexport SCRAM_ARCH={scramArch}\nsource /cvmfs/cms.cern.ch/cmsset_default.sh\nscramv1 project CMSSW {cmsswVersion} > /dev/null\ncd {cmsswVersion}/src\neval `scramv1 runtime -sh`\ncd $_CONDOR_SCRATCH_DIR\n\ntar xzf kamuiPackage.tar.gz\nexport PYTHONPATH=$_CONDOR_SCRATCH_DIR/python:$PYTHONPATH\n\npython3 -c "import json; files=json.load(open(\'fileLists.json\'))[\'$SAMPLE\'][int(\'$IDX\')]; open(\'inputs.txt\',\'w\').write(chr(10).join(files))"\n\nmapfile -t INPUTS < inputs.txt\npython3 -m kamui.select.job {selectionJson} out.root "${{INPUTS[@]}}"\n\nxrdfs {eosRedirector} mkdir -p {outDir}\nxrdcp -f out.root {eosRedirector}/{outDir}/{selectedName}\nxrdcp -f out.root.cutflow.json {eosRedirector}/{outDir}/{cutflowName}\necho "[job] end=$(date)"\n'

JDL = '# Generated by kamui - resubmit with: condor_submit {jdlName}\nuniverse                = vanilla\nexecutable              = $(script)\narguments               = $(sample) $(index)\ntransfer_input_files    = {inputFiles}\nshould_transfer_files   = YES\nwhen_to_transfer_output = ON_EXIT\noutput                  = logs/$(sample)_$(index).out\nerror                   = logs/$(sample)_$(index).err\nlog                     = logs/condor.log\nrequest_memory          = {memoryMB}\nrequest_disk            = {diskKB}\n# LPC worker OS selection. If jobs sit idle forever, try +REQUIRED_OS = "rhel9" instead.\n+DesiredOS              = "EL9"\nx509userproxy           = $ENV(X509_USER_PROXY)\n\nqueue sample,index,script from jobList.txt\n'


def taskDir(taskName, create=True):
    """The job area for a selection task."""
    checkTaskName(taskName)
    d = os.path.join(paths.SELECTION_JOBS_DIR, taskName)
    if create:
        os.makedirs(d, exist_ok=True)
    return d


# A pass applies one selection, so the era names the script. A stacked selection's commas would also split the rows of jobList.txt.
def _scriptName(era):
    return "runSelect_%s.sh" % era


def _jobArea(taskName, sites, eosDir):
    """The job area for a new selection task. Refuses a task that was submitted or whose EOS output directory holds files, and rebuilds an area that was never submitted, such as one a dry run left."""
    checkFreshTask(taskName, "condor")
    checkOutputUnused(sites, eosDir, taskName)
    d = taskDir(taskName)
    if os.listdir(d):
        print(f"  Reusing the job area {d}, since its task was never submitted")
        ## Cleared first, so no stale script or file list can ship with the new jobs
        for entry in os.listdir(d):
            full = os.path.join(d, entry)
            shutil.rmtree(full) if os.path.isdir(full) and not os.path.islink(full) else os.remove(full)
    return d


def packageKamui(d):
    """Ship the kamui package so the worker can import it without a checkout."""
    out = os.path.join(d, "kamuiPackage.tar.gz")
    pkg = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with tarfile.open(out, "w:gz") as tar:
        tar.add(pkg, arcname=os.path.join("python", "kamui"), filter=lambda ti: None if "__pycache__" in ti.name else ti)
    return out


def prepare(plan, sites=None, filesPerJob=None, memoryMB=None, diskKB=4000000, base=None, cmsswVersion=None, scramArch=None):
    """Write a complete condor area for a pass that io.preparePass planned. Returns the job area, the job count and the EOS output directory."""
    sites = sites or loadSites()
    taskName = plan["task"]
    base = (base or sites["stageoutBase"]).rstrip("/")
    eosDir = outputDir(base, taskName, OUTPUT_STAGE)
    cmsswVersion = cmsswVersion or sites["cmssw"]["version"]
    scramArch = scramArch or sites["cmssw"]["scramArch"]
    resolvedSelections = plan["resolvedSelections"]

    d = _jobArea(taskName, sites, eosDir)
    os.makedirs(os.path.join(d, "logs"), exist_ok=True)

    ## One resolved selection per era, since thresholds differ by era
    selectionFiles = {}
    for era in resolvedSelections:
        p = os.path.join(d, "selection_%s.json" % era)
        with open(p, "w") as f:
            json.dump(resolvedSelections[era], f, indent=2)
        selectionFiles[era] = p

    perJob = int(filesPerJob or DEFAULT_FILES_PER_JOB)
    memoryMB = int(memoryMB or DEFAULT_MEMORY_MB)
    chunked, jobRows = {}, []
    for s in plan["samples"]:
        groups = chunk(sorted(set(plan["fileLists"][s["name"]])), perJob)
        chunked[s["name"]] = groups
        jobRows += ["%s,%d,%s" % (s["name"], i, _scriptName(s["era"])) for i in range(len(groups))]

    with open(os.path.join(d, "fileLists.json"), "w") as f:
        json.dump(chunked, f, indent=1)
    with open(os.path.join(d, "jobList.txt"), "w") as f:
        f.write(chr(10).join(jobRows) + chr(10))

    packageKamui(d)

    for era in selectionFiles:
        script = RUN_SCRIPT.format(
            scramArch=scramArch,
            cmsswVersion=cmsswVersion,
            selectionJson=os.path.basename(selectionFiles[era]),
            eosRedirector=sites["eosRedirector"].rstrip("/"),
            outDir=eosDir + "/$SAMPLE",
            selectedName=SELECTED_NAME.format(sample="${SAMPLE}", index="${IDX}"),
            cutflowName=CUTFLOW_NAME.format(sample="${SAMPLE}", index="${IDX}"),
        )
        p = os.path.join(d, _scriptName(era))
        with open(p, "w") as f:
            f.write(script)
        os.chmod(p, os.stat(p).st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)

    inputFiles = ["fileLists.json", "kamuiPackage.tar.gz"] + [os.path.basename(selectionFiles[e]) for e in sorted(selectionFiles)]
    jdlName = "submit.jdl"
    with open(os.path.join(d, jdlName), "w") as f:
        f.write(JDL.format(jdlName=jdlName, inputFiles=",".join(inputFiles), memoryMB=memoryMB, diskKB=diskKB))

    writePassRecord(d, plan, eosDir, fields={"nJobs": len(jobRows), "filesPerJob": perJob, "memoryMB": memoryMB, "outputBase": base}, sites=sites)
    return d, len(jobRows), eosDir


def submit(taskName, dryRun=False, sites=None):
    """Run condor_submit on a selection job area, then record the cluster and publish task.json next to the selected ntuples."""
    d = taskDir(taskName, create=False)
    if dryRun:
        print("  [dryRun] condor_submit %s" % os.path.join(d, "submit.jdl"))
        return 0
    r = runTool(["condor_submit", "submit.jdl"], cwd=d, capture_output=True, text=True)
    print(r.stdout.strip() or r.stderr.strip())
    if r.returncode == 0:
        ## The cluster marks the task as submitted, and lets status ask about this task alone. LPC spreads submissions over several schedds.
        cluster = re.search(r"submitted to cluster (\d+)", r.stdout)
        schedd = re.search(r"submit jobs to (\S+)", r.stdout)
        fields = {}
        if cluster:
            fields["condorCluster"] = int(cluster.group(1))
        if schedd:
            fields["schedd"] = schedd.group(1)
        if fields:
            updateTaskRecord(d, fields)
        sites = sites or loadSites()
        publishRecord(d, sites, taskName, base=readTaskRecord(d)["outputBase"], stage=OUTPUT_STAGE)
    return r.returncode


def missingJobs(taskName, sites=None):
    """Job rows of a selection task whose selected ntuple is not on EOS. Returns (rows, presentCount, expectedCount)."""
    sites = sites or loadSites()
    d = taskDir(taskName, create=False)
    outDir = recordedOutputDir(readTaskRecord(d))
    redirector = sites["eosRedirector"].rstrip("/")
    with open(os.path.join(d, "jobList.txt")) as f:
        rows = [line.strip() for line in f if line.strip()]
    listings, missing = {}, []
    for row in rows:
        sampleName, index = row.split(",")[:2]
        if sampleName not in listings:
            listings[sampleName] = eosListing(redirector, f"{outDir}/{sampleName}")
        if SELECTED_NAME.format(sample=sampleName, index=index) not in listings[sampleName]:
            missing.append(row)
    return missing, len(rows) - len(missing), len(rows)
