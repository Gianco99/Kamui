"""
CRAB3 backend. One CRAB task per sample.
"""

# Import Block

## Standard Python imports
import os
import subprocess

## Kamui modules
from ..configReaders.sites import loadSites
from .common import checkLocalArea, checkTaskName, copyNtupleCode, globalTagArg, outputBase, outputDir, publishRecord, readTaskRecord, recordedOutputDir, resolveTaskDir, taskDir, updateTaskRecord, writeResolvedContent, writeTaskRecord

## Input files per job when neither the flag nor the sample says otherwise
DEFAULT_FILES_PER_JOB = 5
## Each sample's CRAB config is crabConfig_<sample>.py in the job area
CONFIG_PREFIX = "crabConfig_"

CRAB_TEMPLATE = '''# Generated by kamui from the config JSONs; edit those to change it.
# Sample : {sampleName}
# Dataset: {dataset}
from CRABClient.UserUtilities import config
config = config()

config.General.requestName     = {requestName!r}
config.General.workArea        = {workArea!r}
config.General.transferOutputs = True
config.General.transferLogs    = False

config.JobType.pluginName  = 'Analysis'
config.JobType.psetName    = {psetName!r}
config.JobType.pyCfgParams = {pyCfgParams!r}
config.JobType.inputFiles  = {inputFiles!r}
config.JobType.maxMemoryMB = {maxMemoryMB}
config.JobType.numCores    = 1

config.Data.inputDataset     = {dataset!r}
config.Data.inputDBS         = {inputDBS!r}
config.Data.splitting        = 'FileBased'
config.Data.unitsPerJob      = {unitsPerJob}
config.Data.outLFNDirBase    = {outLFNDirBase!r}
config.Data.publication      = False
config.Data.outputDatasetTag = {outputDatasetTag!r}
{totalUnitsLine}{lumiMaskLine}
config.Site.storageSite = {storageSite!r}
'''


def _requestName(taskName, sampleName):
    # CRAB caps requestName at 100 characters.
    name = f"{taskName}__{sampleName}"
    return name[:100]


def _checkRequestNames(taskName, samples):
    seen = {}
    for s in samples:
        r = _requestName(taskName, s["name"])
        if r in seen:
            raise ValueError(f"Task name '{taskName}' is too long: samples '{seen[r]}' and '{s['name']}' both truncate to the same CRAB requestName. Use a shorter --task.")
        seen[r] = s["name"]


def _configName(sampleName):
    return f"{CONFIG_PREFIX}{sampleName}.py"


def _sampleOfConfig(configPath):
    """The sample a crabConfig file was written for, from its name."""
    return os.path.basename(configPath)[len(CONFIG_PREFIX):-len(".py")]


def prepare(samples, taskName, sites=None, unitsPerJob=None, maxFiles=None, maxMemoryMB=2500, base=None):
    """Write one crabConfig per sample into the task directory. Returns their paths and the output base."""
    sites = sites or loadSites()
    checkTaskName(taskName)
    _checkRequestNames(taskName, samples)
    base = outputBase(sites, "crab", base)
    eosDir = outputDir(base, taskName)
    ## CRAB ships the compiled code of the area it is submitted from, so that build must be current
    area = checkLocalArea()
    d = resolveTaskDir(taskName, sites, eosDir)
    ## CRAB reads the code at each crab submit, and resubmit runs one again for a sample that failed to go out
    pset, tables = copyNtupleCode(d)

    contentCache = {}
    effective = {s["name"]: int(unitsPerJob or s.get("unitsPerJob") or DEFAULT_FILES_PER_JOB) for s in samples}
    written = []
    for s in samples:
        key = (s["content"], bool(s["isMC"]), s["era"])
        if key not in contentCache:
            contentCache[key] = writeResolvedContent(d, s["content"], bool(s["isMC"]), s["era"])
        contentJson = contentCache[key]

        tag = globalTagArg(contentJson, s["era"], bool(s["isMC"]), sites)
        inputDBS = "phys03" if "phys03" in s["dasInstance"] else "global"
        lumiMaskLine = f"config.Data.lumiMask = {s['lumiMask']!r}\n" if s.get("lumiMask") else ""

        text = CRAB_TEMPLATE.format(
            sampleName=s["name"],
            dataset=s["dataset"],
            requestName=_requestName(taskName, s["name"]),
            workArea=os.path.join(d, "crab"),
            psetName=pset,
            pyCfgParams=[
                f"content={contentJson}",
                f"isMC={'True' if s['isMC'] else 'False'}",
            ] + ([f"globalTag={tag}"] if tag else []),
            inputFiles=[contentJson, tables],
            maxMemoryMB=maxMemoryMB,
            inputDBS=inputDBS,
            unitsPerJob=effective[s["name"]],
            outLFNDirBase=eosDir,
            outputDatasetTag=s["name"][:99],
            lumiMaskLine=lumiMaskLine,
            ## With FileBased splitting, totalUnits caps the number of input files
            totalUnitsLine=f"config.Data.totalUnits     = {maxFiles}\n" if maxFiles else "",
            storageSite=sites["crabStorageSite"],
        )
        path = os.path.join(d, _configName(s["name"]))
        with open(path, "w") as f:
            f.write(text)
        written.append(path)

    ## CRAB ships the release it is submitted from, so task.json records the environment's CMSSW.
    writeTaskRecord(d, {
        "task": taskName, "backend": "crab",
        "samples": [s["name"] for s in samples],
        "content": sorted({s["content"] for s in samples}),
        "unitsPerJob": effective, "maxFiles": maxFiles, "maxMemoryMB": maxMemoryMB, "localArea": area,
        "cmssw": {"version": os.environ.get("CMSSW_VERSION"), "scramArch": os.environ.get("SCRAM_ARCH")},
        "outputDir": eosDir,
    }, samples=samples, resolvedContent=contentCache.values())
    return written, base


# The cvmfs crab wrapper exits zero when the CMSSW environment is missing, so the project directory confirms a submission.
def _projectDir(configPath):
    """Where `crab submit` puts its work area for a config, from the config itself."""
    values = {}
    for line in open(configPath):
        for key in ("requestName", "workArea"):
            if f"General.{key}" in line and "=" in line:
                values[key] = line.split("=", 1)[1].strip().strip("'\"")
    if len(values) != 2:
        return ""
    return os.path.join(values["workArea"], "crab_" + values["requestName"])


def submit(configPaths, dryRun=False, sites=None, taskName=None, base=None, maxMemoryMB=None):
    """Run `crab submit` for each generated config, and record in task.json which samples went out and which failed. maxMemoryMB, when given, replaces the memory the configs ask for. Returns the configs that went out and the ones that failed."""
    ## A config parameter given after the config file overrides the value the file sets
    override = [f"JobType.maxMemoryMB={int(maxMemoryMB)}"] if maxMemoryMB else []
    ok, bad = [], []
    for p in configPaths:
        if dryRun:
            print(f"  [dryRun] {' '.join(['crab', 'submit', '-c', p] + override)}")
            ok.append(p)
            continue
        r = subprocess.run(["crab", "submit", "-c", p] + override, capture_output=True, text=True)
        project = _projectDir(p)
        if r.returncode != 0 or not os.path.isdir(project):
            reason = r.stderr.strip().splitlines()[-1:] or r.stdout.strip().splitlines()[-3:]
            print(f"  FAILED {os.path.basename(p)}: {reason}")
            bad.append(p)
        else:
            print(f"  Submitted {os.path.basename(p)}")
            ok.append(p)
    if not dryRun and taskName:
        ## A sample whose submit failed has no crab project, so only the record keeps it in view for status and resubmit
        d = taskDir(taskName, create=False)
        rec = readTaskRecord(d)
        sent = {_sampleOfConfig(p) for p in ok}
        updateTaskRecord(d, {
            "submittedSamples": sorted(set(rec.get("submittedSamples", [])) | sent),
            "failedSubmissions": sorted((set(rec.get("failedSubmissions", [])) | {_sampleOfConfig(p) for p in bad}) - sent),
        })
        if ok:
            publishRecord(d, sites or loadSites(), taskName, base)
    return ok, bad


def wasSubmitted(taskName):
    """Whether crab submit ever ran for the task. A dry run writes the configs and records no crab submit."""
    d = taskDir(taskName, create=False)
    rec = readTaskRecord(d)
    return os.path.isdir(os.path.join(d, "crab")) or bool(rec.get("submittedSamples") or rec.get("failedSubmissions"))


# CRAB tracks its own failed jobs and writes retried output to the same place, so a retry needs no new job list or destination.
def resubmit(taskName, dryRun=False, sites=None, memoryMB=None):
    """`crab submit` again for each sample whose submission failed, and `crab resubmit` over every other crab project in the task. memoryMB, when given, is the memory every resubmitted job asks for. Returns the number of projects asked to resubmit and the samples that still failed to submit."""
    d = taskDir(taskName, create=False)
    rec = readTaskRecord(d)
    retry = [os.path.join(d, _configName(name)) for name in rec.get("failedSubmissions", [])]
    workArea = os.path.join(d, "crab")
    if not os.path.isdir(workArea) and not retry:
        raise FileNotFoundError(f"No crab work area at {workArea}")
    retryProjects = {_projectDir(p) for p in retry}
    maxMemory = ["--maxmemory", str(int(memoryMB))] if memoryMB else []
    n = 0
    for proj in sorted(os.listdir(workArea)) if os.path.isdir(workArea) else []:
        full = os.path.join(workArea, proj)
        if not os.path.isdir(full) or full in retryProjects:
            continue
        n += 1
        if dryRun:
            print(f"  [dryRun] {' '.join(['crab', 'resubmit', '-d', full] + maxMemory)}")
            continue
        print(f"\n=== {proj}")
        subprocess.run(["crab", "resubmit", "-d", full] + maxMemory)
    if not retry:
        return n, []

    ## crab submit refuses a config whose project directory exists, and a failed submission can leave one behind
    leftover = [p for p in retry if os.path.isdir(_projectDir(p))]
    for p in leftover:
        print(f"\n  {_sampleOfConfig(p)}: its failed submission left {_projectDir(p)}. Check it with crab status -d {_projectDir(p)}, and if CRAB never got the task, remove that directory and run resubmit again.")
    retry = [p for p in retry if p not in leftover]
    bad = []
    if retry:
        print(f"\n=== Submitting again {len(retry)} sample(s) whose crab submit failed")
        ## The recorded outputDir is <base>/ntuples/<task>
        bad = submit(retry, dryRun=dryRun, sites=sites, taskName=taskName, base=recordedOutputDir(rec).rsplit("/", 2)[0], maxMemoryMB=memoryMB)[1]
    return n, [_sampleOfConfig(p) for p in bad + leftover]


def status(taskName):
    """`crab status` over every crab project in a task directory, after naming the samples whose crab submit failed."""
    d = taskDir(taskName, create=False)
    rec = readTaskRecord(d)
    failed = rec.get("failedSubmissions", [])
    if failed:
        print(f"\nNever submitted, since crab submit failed: {', '.join(failed)}. Run ./kamui resubmit --task {taskName} to try them again.")
    workArea = os.path.join(d, "crab")
    if not os.path.isdir(workArea):
        if failed:
            return
        ## A dry run writes the configs and records no crab submit
        if not rec.get("submittedSamples"):
            print("\nNot submitted, since the job area holds no crab work area")
            return
        raise FileNotFoundError(f"No crab work area at {workArea}")
    for proj in sorted(os.listdir(workArea)):
        full = os.path.join(workArea, proj)
        if not os.path.isdir(full):
            continue
        print(f"\n=== {proj}")
        subprocess.run(["crab", "status", "-d", full])
