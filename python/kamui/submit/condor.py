## Input files per job when neither the flag nor the sample says otherwise
DEFAULT_FILES_PER_JOB = 5
## Condor JobStatus codes. A held job stays on the queue without running until someone releases or removes it.
JOB_ACTIVE = (1, 2, 6, 7)                       # Idle, running, transferring output, suspended
JOB_HELD = 5

RUN_SCRIPT = r'''#!/bin/bash
# Generated by kamui. $1 = sample name, $2 = job index
set -e
SAMPLE=$1
IDX=$2
echo "[job] sample=$SAMPLE index=$IDX host=$(hostname) start=$(date)"

export SCRAM_ARCH={scramArch}
source /cvmfs/cms.cern.ch/cmsset_default.sh
scramv1 project CMSSW {cmsswVersion} > /dev/null
# A fresh release lacks the Kamui plugins, so unpack the ones compiled in the submitting area
tar -xzf {areaTarball} -C {cmsswVersion}
cd {cmsswVersion}/src
eval `scramv1 runtime -sh`
cd $_CONDOR_SCRATCH_DIR

python3 - "$SAMPLE" "$IDX" <<'PY'
import json, os, sys
sample, idx = sys.argv[1], sys.argv[2]
files = json.load(open("fileLists.json"))[sample][int(idx)]
open("inputs.txt", "w").write(",".join(files))
masks = json.load(open("lumiMasks.json")) if os.path.exists("lumiMasks.json") else {{}}
open("lumiMask.txt", "w").write(masks.get(sample, ""))
PY
INPUTS=$(cat inputs.txt)
MASK=$(cat lumiMask.txt)

cmsRun ntuple_cfg.py content={contentJson} isMC={isMC} {globalTagArg}\
    inputFiles=$INPUTS outputFile=out.root maxEvents={maxEvents} ${{MASK:+lumiMask=$MASK}}

xrdfs {eosRedirector} mkdir -p {outDir}
DEST={eosRedirector}/{outDir}/${{SAMPLE}}_ntuple_${{IDX}}.root
xrdcp -f out.root "$DEST"
echo "[job] wrote $DEST"
echo "[job] end=$(date)"
'''

JDL = '''# Generated by kamui - resubmit with: condor_submit {jdlName}
universe                = vanilla
executable              = $(script)
arguments               = $(sample) $(index)
transfer_input_files    = {inputFiles}
should_transfer_files   = YES
when_to_transfer_output = ON_EXIT
output                  = {logDir}/$(sample)_$(index).out
error                   = {logDir}/$(sample)_$(index).err
log                     = {logDir}/condor.log
request_memory          = {memoryMB}
request_disk            = {diskKB}
# LPC worker OS selection. If jobs sit idle forever, try +REQUIRED_OS = "rhel9" instead.
+DesiredOS              = "EL9"
x509userproxy           = $ENV(X509_USER_PROXY)

queue sample,index,script from {jobListName}
'''


def _scriptName(presetName, isMC, era):
    """One run script per content preset, data/MC flavor and era."""
    return f"runJob_{contentStem(presetName)}_{'mc' if isMC else 'data'}_{era}.sh"


# fileLists maps a sample name to the list of LFNs it should run over, resolved by the caller from DAS or EOS.
def prepare(samples, taskName, fileLists, sites=None, filesPerJob=None, maxFiles=None, maxEvents=-1, memoryMB=2500, diskKB=4000000, cmsswVersion=None, scramArch=None, base=None):
    """Write a complete condor submission area. Returns the directory, the job count and the output base. maxFiles is the cap the file lists were cut to, recorded so a selection pass knows they cover only part of a dataset."""
    sites = sites or loadSites()
    checkTaskName(taskName)
    base = outputBase(sites, "condor", base)
    eosDir = outputDir(base, taskName)
    # The release lives in config/sites.json
    cmsswVersion = cmsswVersion or sites["cmssw"]["version"]
    scramArch = scramArch or sites["cmssw"]["scramArch"]
    area = checkLocalArea(cmsswVersion, scramArch)
    d = resolveTaskDir(taskName, sites, eosDir)
    os.makedirs(os.path.join(d, "logs"), exist_ok=True)

    staged, masks = {}, {}
    for s in samples:
        mask = s.get("lumiMask")
        if mask and mask not in staged:
            staged[mask] = f"lumiMask{len(staged)}.json"
            dest = os.path.join(d, staged[mask])
            if re.match(r"https?://", mask):
                with urllib.request.urlopen(mask, timeout=120) as r, open(dest, "wb") as f:
                    f.write(r.read())
            else:
                shutil.copyfile(mask, dest)
            with open(dest) as f:
                json.load(f)
        if mask:
            masks[s["name"]] = staged[mask]

    contentCache = {}
    chunked, jobRows = {}, []
    effective = {}
    dropped = []
    for s in samples:
        lfns = fileLists.get(s["name"], [])
        if len(set(lfns)) != len(lfns):
            print(f"  Warning: {s['name']} listed {len(lfns) - len(set(lfns))} duplicate file(s); keeping one copy of each")
            lfns = sorted(set(lfns))
        if not lfns:
            dropped.append(s["name"])
            continue
        key = (s["content"], bool(s["isMC"]), s["era"])
        if key not in contentCache:
            contentCache[key] = writeResolvedContent(d, s["content"], bool(s["isMC"]), s["era"])
        perJob = int(filesPerJob or s.get("unitsPerJob") or DEFAULT_FILES_PER_JOB)
        effective[s["name"]] = perJob
        groups = chunk(lfns, perJob)
        chunked[s["name"]] = [[sites["sourceRedirector"].rstrip("/") + "/" + f if not f.startswith("root:") else f for f in g] for g in groups]
        jobRows += [f"{s['name']},{i},{_scriptName(*key)}" for i in range(len(groups))]

    if dropped:
        print(f"  Warning: no input files found, so {len(dropped)} sample(s) got no jobs: {', '.join(dropped)}")

    with open(os.path.join(d, "fileLists.json"), "w") as f:
        json.dump(chunked, f, indent=1)
    with open(os.path.join(d, "jobList.txt"), "w") as f:
        f.write("\n".join(jobRows) + "\n")
    if masks:
        with open(os.path.join(d, "lumiMasks.json"), "w") as f:
            json.dump(masks, f, indent=1)

    # A task may mix content presets and MC with data, so each combination gets its own run script
    for (preset, isMC, era), contentJson in contentCache.items():
        tag = globalTagArg(contentJson, era, isMC, sites)
        script = RUN_SCRIPT.format(
            scramArch=scramArch,
            cmsswVersion=cmsswVersion,
            areaTarball=AREA_TARBALL,
            contentJson=os.path.basename(contentJson),
            isMC="True" if isMC else "False",
            globalTagArg=f"globalTag={tag} " if tag else "",
            maxEvents=maxEvents,
            eosRedirector=sites["eosRedirector"].rstrip("/"),
            outDir=eosDir + "/$SAMPLE",
        )
        p = os.path.join(d, _scriptName(preset, isMC, era))
        with open(p, "w") as f:
            f.write(script)
        os.chmod(p, os.stat(p).st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)

    inputFiles = ["fileLists.json", packLocalArea(d, area)] + copyNtupleCode(d) + list(contentCache.values()) + (["lumiMasks.json"] + sorted(set(masks.values())) if masks else [])
    jdlName = "submit.jdl"
    with open(os.path.join(d, jdlName), "w") as f:
        f.write(JDL.format(jdlName=jdlName, inputFiles=",".join(inputFiles), memoryMB=memoryMB, diskKB=diskKB, logDir="logs", jobListName="jobList.txt"))

    submitted = [s for s in samples if s["name"] in chunked]
    writeTaskRecord(d, {
        "task": taskName, "backend": "condor", "nJobs": len(jobRows),
        "samples": sorted(chunked), "droppedSamples": sorted(dropped), "filesPerJob": effective,
        "maxFiles": maxFiles, "maxEvents": maxEvents, "memoryMB": memoryMB, "localArea": area,
        "nInputFiles": {k: sum(len(g) for g in v) for k, v in sorted(chunked.items())},
        "outputDir": eosDir,
    }, samples=submitted, sites=sites, resolvedContent=contentCache.values())
    return d, len(jobRows), base


def submit(taskName, dryRun=False, base=None):
    """Run `condor_submit` on the task's JDL."""
    d = taskDir(taskName, create=False)
    jdl = os.path.join(d, "submit.jdl")
    if dryRun:
        print(f"  [dryRun] condor_submit {jdl}")
        return 0
    r = runTool(["condor_submit", "submit.jdl"], cwd=d, capture_output=True, text=True)
    print(r.stdout.strip() or r.stderr.strip())
    if r.returncode == 0:
        # Keep the cluster id from "N job(s) submitted to cluster 12345." so status can ask about this task alone.
        cluster = re.search(r"submitted to cluster (\d+)", r.stdout)
        # LPC spreads a submission over several schedds, and condor_q asks the default one unless told otherwise.
        schedd = re.search(r"submit jobs to (\S+)", r.stdout)
        fields = {}
        if cluster:
            fields["condorCluster"] = int(cluster.group(1))
        if schedd:
            fields["schedd"] = schedd.group(1)
        if fields:
            updateTaskRecord(d, fields)
        publishRecord(d, loadSites(), taskName, base)
    return r.returncode


# What a finished job leaves on EOS. A job that died anywhere before the copy leaves nothing.
def _expectedOutput(sampleName, index):
    return f"{sampleName}_ntuple_{index}.root"


def missingJobs(taskName, sites=None):
    """Job rows from the task whose outputs are not on EOS. Returns (rows, presentCount, expectedCount)."""
    sites = sites or loadSites()
    d = taskDir(taskName, create=False)
    info = readTaskRecord(d)
    if info.get("backend") != "condor":
        raise ValueError(f"Task '{taskName}' ran on {info.get('backend')}; this needs a condor task")
    eosDir = recordedOutputDir(info)
    if not eosDir:
        raise ValueError(f"Task '{taskName}' has no output directory recorded, so its outputs cannot be located")
    redirector = sites["eosRedirector"].rstrip("/")

    rows = [line.strip() for line in open(os.path.join(d, "jobList.txt")) if line.strip()]
    listings, missing, nPresent, nExpected = {}, [], 0, 0
    for row in rows:
        sampleName, index = row.split(",")[0], row.split(",")[1]
        if sampleName not in listings:
            listings[sampleName] = eosListing(redirector, f"{eosDir}/{sampleName}")
        nExpected += 1
        if _expectedOutput(sampleName, index) in listings[sampleName]:
            nPresent += 1
        else:
            missing.append(row)
    return missing, nPresent, nExpected


# LPC puts each submission, a retry included, on whichever schedd it picks then, so every cluster has to be asked about on its own schedd.
def submissions(info):
    """The (schedd, cluster) pair of the task's first submission and of every retry. A pair with no schedd asks the default one."""
    return [(entry.get("schedd"), int(entry["condorCluster"])) for entry in [info] + list(info.get("retries", [])) if entry.get("condorCluster")]


def queueState(info):
    """What condor_q says about every recorded submission. Returns the active and held job counts, the held count of each pair, and the pairs condor_q could not answer for."""
    state = {"active": 0, "held": 0, "heldPairs": {}, "unknown": []}
    for schedd, cluster in submissions(info):
        cmd = ["condor_q"] + (["-name", schedd] if schedd else []) + [str(cluster), "-af", "JobStatus"]
        try:
            r = runTool(cmd, capture_output=True, text=True, timeout=120)
        except (OSError, subprocess.SubprocessError):
            r = None
        words = r.stdout.split() if r is not None and r.returncode == 0 else None
        ## With -af JobStatus condor_q prints only numbers, so other text means it did not answer, as when the LPC wrapper exits 0 with 'All queues are empty' for a schedd the pool does not know
        if words is None or not all(w.isdigit() for w in words):
            state["unknown"].append((schedd, cluster))
            continue
        codes = [int(w) for w in words]
        state["active"] += sum(c in JOB_ACTIVE for c in codes)
        if JOB_HELD in codes:
            state["heldPairs"][(schedd, cluster)] = codes.count(JOB_HELD)
            state["held"] += codes.count(JOB_HELD)
    return state


def _queueLines(state):
    """What the user should know about a queueState, each with what to do about it. Empty when nothing of the task is left on the queue."""
    lines = []
    if state["active"]:
        lines.append(f"{state['active']} job(s) of this task are still idle or running. Wait for them to finish.")
    for (schedd, cluster), n in state["heldPairs"].items():
        name = schedd or "<schedd>"
        lines.append(f"{n} job(s) of cluster {cluster} are held and will not run again by themselves. See why with condor_q -hold -name {name} {cluster}, and remove them with: condor_rm -name {name} -constraint 'ClusterId == {cluster} && JobStatus == {JOB_HELD}'")
    for schedd, cluster in state["unknown"]:
        lines.append(f"condor_q could not say what cluster {cluster} on {schedd or 'the default schedd'} is doing, so its jobs may still be running. Try again later.")
    return lines


def status(taskName, sites=None):
    """Show a condor task's jobs on each schedd it was submitted to, then how many of its outputs are on EOS."""
    d = taskDir(taskName, create=False)
    info = readTaskRecord(d)
    for retry in info.get("retries", []):
        print(f"Retry {retry['retry']}: {retry['nJobs']} job(s) at {retry.get('submittedAt')}, logs in {retry['logDir']}")
    pairs = submissions(info)
    ## resubmit and submit also count a task with no recorded cluster as never submitted
    if not pairs:
        print("\nNot submitted, since the record holds no condor cluster")
        return 0
    for schedd, cluster in pairs:
        cmd = ["condor_q", "-nobatch"] + (["-name", schedd] if schedd else []) + [str(cluster)]
        try:
            runTool(cmd)
        except OSError as e:
            print(f"\nCould not run condor_q: {e}")

    lines = _queueLines(queueState(info))
    for line in lines:
        print(line)
    try:
        missing, nPresent, nExpected = missingJobs(taskName, sites)
    except RuntimeError as e:
        print(f"Outputs  unknown, since EOS could not be listed: {e}")
        return 0
    print(f"Outputs  {nPresent}/{nExpected} present on EOS")
    if missing and not lines:
        print(f"  Run ./kamui resubmit --task {taskName} to rerun the {len(missing)} missing job(s)")
    return 0


def _nextRetry(d):
    """The first retry number not already used, so an earlier attempt's logs are never overwritten."""
    n = 1
    while os.path.exists(os.path.join(d, "logs", f"retry{n}")) or os.path.exists(os.path.join(d, f"jobList.retry{n}.txt")):
        n += 1
    return n


# A retry keeps the task's run scripts and resolved content and adds its own job list, JDL and log directory, so its outputs land on EOS beside the finished ones.
def resubmit(taskName, dryRun=False, sites=None, rows=None, force=False, memoryMB=None):
    """Submit only the jobs of a task whose outputs are missing. Refuses while any of its jobs may still be on the queue, unless forced. memoryMB, when given, replaces the memory the retried jobs ask for, which is otherwise what the task's submit asked for. Returns (retryNumber, nJobs, returncode)."""
    sites = sites or loadSites()
    d = taskDir(taskName, create=False)
    if rows is None:
        rows = missingJobs(taskName, sites)[0]
    if not rows:
        return None, 0, 0

    ## A job still on the queue has not failed, and running it again would write the same output twice
    lines = _queueLines(queueState(readTaskRecord(d)))
    for line in lines:
        print(f"  {line}")
    if lines and not force:
        raise RuntimeError("Refusing to resubmit until the jobs above are off the queue. Pass --forceResubmit to submit anyway.")

    n = _nextRetry(d)
    logDir = os.path.join("logs", f"retry{n}")
    jobListName = f"jobList.retry{n}.txt"
    if dryRun:
        # Writing nothing here keeps the retry number free, so a dry run does not push the real attempt to retry2.
        memory = f", {int(memoryMB)} MB each" if memoryMB else ""
        print(f"  [dryRun] condor_submit submit.retry{n}.jdl   ({len(rows)} job(s){memory}, logs would go to {logDir})")
        return n, len(rows), 0

    os.makedirs(os.path.join(d, logDir), exist_ok=True)
    with open(os.path.join(d, jobListName), "w") as f:
        f.write("\n".join(rows) + "\n")

    with open(os.path.join(d, "submit.jdl")) as f:
        original = f.read()
    jdlName = f"submit.retry{n}.jdl"
    jdl = original.replace("queue sample,index,script from jobList.txt", f"queue sample,index,script from {jobListName}")
    jdl = jdl.replace("output                  = logs/$(sample)_$(index).out", f"output                  = {logDir}/$(sample)_$(index).out")
    jdl = jdl.replace("error                   = logs/$(sample)_$(index).err", f"error                   = {logDir}/$(sample)_$(index).err")
    jdl = jdl.replace("log                     = logs/condor.log", f"log                     = {logDir}/condor.log")
    jdl = jdl.replace("# Generated by kamui - resubmit with: condor_submit submit.jdl", f"# Generated by kamui - retry {n} of task {taskName}. Resubmit with: condor_submit {jdlName}")
    nMemory = 1
    if memoryMB:
        jdl, nMemory = re.subn(r"^(request_memory +=) .*$", rf"\g<1> {int(memoryMB)}", jdl, flags=re.M)
    if f"from {jobListName}" not in jdl or logDir not in jdl or nMemory != 1:
        raise ValueError(f"Could not build a retry JDL from {os.path.join(d, 'submit.jdl')}; its format has changed")
    with open(os.path.join(d, jdlName), "w") as f:
        f.write(jdl)

    r = runTool(["condor_submit", jdlName], cwd=d, capture_output=True, text=True)
    print(r.stdout.strip() or r.stderr.strip())
    if r.returncode == 0:
        _recordRetry(d, n, len(rows), logDir, jdlName, r.stdout, memoryMB)
    return n, len(rows), r.returncode


def _recordRetry(d, n, nJobs, logDir, jdlName, stdout, memoryMB=None):
    """Append the retry to task.json without disturbing the original submission's record."""
    entry = {
        "retry": n,
        "nJobs": nJobs,
        "logDir": logDir,
        "jdl": jdlName,
        "submittedAt": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
    }
    if memoryMB:
        entry["memoryMB"] = int(memoryMB)
    m = re.search(r"submitted to cluster (\d+)", stdout or "")
    if m:
        entry["condorCluster"] = int(m.group(1))
    m = re.search(r"submit jobs to (\S+)", stdout or "")
    if m:
        entry["schedd"] = m.group(1)
    updateTaskRecord(d, {"retries": readTaskRecord(d).get("retries", []) + [entry]})
